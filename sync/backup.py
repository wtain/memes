"""The table list of the prod backup (epic environment-data-sync, P5d-T7).

    python -m sync.backup --write    # rewrite deploy/prod/backup.tables from the registry
    python -m sync.backup --check    # exit 1 when the committed file differs (the guard test does the same)
    python -m sync.backup            # print the list

`deploy/prod/backup.sh` and `restore.sh` read `backup.tables` (one table name per line) and dump/restore exactly those tables: the class P
tables of `sync.registry`, the only data that exists on prod and nowhere else. The file is generated so it cannot drift from the registry.
Standard library plus sync.registry only.
"""
from __future__ import annotations

import sys
from pathlib import Path

from sync import registry
from sync.model import Klass

TABLES_FILE = Path(__file__).resolve().parents[1] / "deploy" / "prod" / "backup.tables"
HEADER = "# generated by `python -m sync.backup --write` from sync/registry.py (class P); do not edit by hand\n"


def tables() -> list[str]:
    return registry.names(Klass.P)


def render() -> str:
    return HEADER + "".join(t + "\n" for t in tables())


def main(argv: list[str]) -> int:
    mode = argv[1] if len(argv) > 1 else ""
    if mode == "--write":
        TABLES_FILE.write_bytes(render().encode("utf-8"))
        return 0
    if mode == "--check":
        current = TABLES_FILE.read_bytes().decode("utf-8") if TABLES_FILE.exists() else None
        if current != render():
            sys.stderr.write("deploy/prod/backup.tables is stale: run `python -m sync.backup --write`\n")
            return 1
        return 0
    if mode:
        sys.stderr.write("usage: python -m sync.backup [--write|--check]\n")
        return 2
    sys.stdout.write(render())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
